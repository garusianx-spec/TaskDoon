/**
 * Seed dataset for the workspace.
 *
 * Dates are expressed as offsets from a fixed anchor so the board always contains overdue,
 * due-today and upcoming work regardless of when the app is opened. `ANCHOR` is resolved at
 * module scope on the client; the server renders against the same clock within a request.
 */
const NOW = new Date();

const at = (dayOffset: number, hours = 9, minutes = 0): string => {
  const date = new Date(NOW);
  date.setDate(date.getDate() + dayOffset);
  date.setHours(hours, minutes, 0, 0);
  return date.toISOString();
};

const dateOnly = (dayOffset: number): string => {
  const date = new Date(NOW);
  date.setDate(date.getDate() + dayOffset);
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
};

