import {base,check,eventually,finish,launch,out,visible,watchConsole} from '../lib/harness.mjs';
const browser=await launch();
const page=await (await browser.newContext({viewport:{width:1440,height:900}})).newPage();
watchConsole(page);
try {
 await page.goto(base+'/tasks');
 const rail=page.getByRole('navigation',{name:'ناوبری اصلی'});
 await rail.getByRole('button',{name:/^فضای کاری فعال/}).click();
 await page.getByRole('menuitem',{name:/پارس‌داده/}).click();
 await rail.getByRole('button',{name:'ایجاد سریع'}).click();
 await page.getByRole('menuitem',{name:'پروژه جدید',exact:true}).click();
 const form=page.getByRole('dialog',{name:'پروژه جدید',exact:true});
 const title='پروژه حافظه سازمانی';
 await form.getByLabel('نام پروژه').fill(title);
 await form.getByRole('button',{name:'ایجاد پروژه',exact:true}).click();
 await form.waitFor({state:'hidden'});
 await rail.getByRole('link',{name:'گفتگوها',exact:true}).click();
 const sidebar=page.getByRole('complementary',{name:'ستون زمینه'});
 check(await eventually(async()=>await sidebar.getByRole('button').filter({hasText:title}).count()===1),'one project produces exactly one chat list item');
 await sidebar.getByRole('button').filter({hasText:title}).click();
 await page.getByRole('textbox',{name:`نوشتن پیام در ${title}`}).fill('تاریخچه ماندگار');
 await page.getByRole('button',{name:'ارسال پیام',exact:true}).click();
 await rail.getByRole('link',{name:'پروژه‌ها و وظایف'}).click();
 const tree=page.getByRole('navigation',{name:'درخت پروژه‌ها'});
 await tree.getByRole('button',{name:new RegExp(title)}).first().hover();
 await tree.getByRole('button',{name:`حذف پروژه ${title}`,exact:true}).click();
 await page.getByRole('dialog',{name:`حذف پروژه «${title}»`}).getByRole('button',{name:'انتقال به سطل زباله'}).click();
 await rail.getByRole('link',{name:'گفتگوها',exact:true}).click();
 check(await sidebar.getByRole('button').filter({hasText:title}).count()===0,'deleted project chat leaves the active list');
 await sidebar.getByRole('button',{name:'بایگانی',exact:true}).click();
 await sidebar.getByRole('button').filter({hasText:title}).click();
 check(await visible(page.getByText('تاریخچه ماندگار',{exact:true})),'archive preserves message history');
 await page.getByText('تاریخچه ماندگار',{exact:true}).hover();
 check(await page.getByRole('button',{name:'پاسخ به پیام',exact:true}).count()===0,'archived messages do not mount mutable action controls');
 check(await page.getByRole('textbox',{name:`نوشتن پیام در ${title}`}).count()===0,'archived conversation has no composer');
 check(await visible(page.getByText(/برای همیشه بایگانی شده/)),'archive explicitly explains its permanent read-only state');
 await page.setViewportSize({width:1280,height:900});
 await page.screenshot({path:`${out}/phase4_archive_1280.png`,fullPage:true});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),'desktop archive has no horizontal overflow');
 await page.setViewportSize({width:375,height:812});
 await page.screenshot({path:`${out}/phase4_archive_375.png`,fullPage:true});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),'mobile archive has no horizontal overflow');
 await page.getByRole('button',{name:'بازگشت به فهرست گفتگوها',exact:true}).click();
 await page.screenshot({path:`${out}/phase4_archive_list_375.png`,fullPage:true});
 check(await visible(sidebar.getByRole('button',{name:'حذف دائمی گفتگوی بایگانی‌شده'})),'manual archive deletion is accessible on mobile');
 await page.setViewportSize({width:1280,height:900});
 await sidebar.getByRole('button',{name:'حذف دائمی گفتگوی بایگانی‌شده'}).click();
 const confirm=page.getByRole('dialog',{name:'حذف دائمی گفتگوی بایگانی‌شده'});
 check(await eventually(async()=>await confirm.getByRole('button',{name:'انصراف',exact:true}).evaluate(el=>el===document.activeElement)),'destructive confirmation initially focuses Cancel');
 await page.keyboard.press('Escape');
 check(await eventually(async()=>await confirm.count()===0),'Escape cancels without deleting history');
 check(await sidebar.getByRole('button',{name:'حذف دائمی گفتگوی بایگانی‌شده'}).evaluate(el=>el===document.activeElement),'closing confirmation restores focus to the archive action');
 await sidebar.getByRole('button',{name:'حذف دائمی گفتگوی بایگانی‌شده'}).click();
 await confirm.screenshot({path:`${out}/phase4_archive_delete.png`});
 await confirm.getByRole('button',{name:'حذف دائمی',exact:true}).click();
 check(await visible(confirm.getByText('نام گفتگو را دقیق وارد کنید.')),'manual deletion requires named confirmation');
 await confirm.getByRole('textbox',{name:'نام گفتگو برای تأیید'}).fill(title);
 await confirm.getByRole('button',{name:'حذف دائمی',exact:true}).click();
 check(await eventually(async()=>await sidebar.getByRole('button').filter({hasText:title}).count()===0),'explicit manual deletion removes the archived chat');
} catch(error){check(false,error.message);} finally {await finish(browser);}
