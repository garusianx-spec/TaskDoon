function section(
  id: string,
  type: SiteSection['type'],
  content: Omit<Partial<SiteSection>, 'id' | 'type'> = {},
): SiteSection {
  return { id, type, visible: true, ...content };
}

function document(
  kind: SiteDocumentKind,
  slug: string,
  title: string,
  description: string,
  sections: SiteSection[],
  data: Record<string, unknown> = {},
  published = true,
): SeedDocument {
  return {
    kind,
    slug,
    title,
    description,
    data,
    published,
    sections: sections.map((block, sortOrder) => ({ ...block, sortOrder })),
    seo: { title: `${title} | تسک‌دون`, description, noIndex: !published },
  };
}

function closing(id: string, title = 'همین امروز همکاری هوشمندانه‌تر را تجربه کنید'): SiteSection {
  return section(id, 'cta', {
    title,
    description: 'فضای کاری تیمتان را بسازید، همکاران را دعوت کنید و اولین پروژه مشترک را جلو ببرید.',
    cta: start,
    secondaryCta: demo,
    variant: 'brand',
    layout: 'center',
  });
}

function featureDocument(
  slug: string,
  title: string,
  description: string,
  blocks: SiteSection[],
): SeedDocument {
  return document(
    'feature',
    slug,
    title,
    description,
    [
      section(`${slug}-hero`, 'hero', {
        title,
        description,
        cta: start,
        secondaryCta: { label: 'مشاهده همه امکانات', href: '/features' },
        layout: 'split',
      }),
      ...blocks,
      closing(`${slug}-cta`),
    ],
    { category: 'product' },
  );
}

